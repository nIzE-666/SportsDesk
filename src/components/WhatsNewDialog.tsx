const SEEN_KEY = 'sportsdesk.whatsnew.seen';

export function WhatsNewDialog() {
  const [visible, setVisible] = useState(false);
  const [current, setCurrent] = useState<ChangeNotes | null>(null);

  useEffect(() => {
    if (!isTauriRuntime()) return;
    void (async () => {
      try {
        const mod = await import('@tauri-apps/api/app');
        const version = await mod.getVersion();
        const seen = getString(SEEN_KEY);
        if (seen === version) return;
        // Новой установке «Что нового» не нужно — её встречает мастер настройки.
        if (onboardingBootDecision().show) {
          setString(SEEN_KEY, version);
          return;
        }
        const notes = WHATS_NEW.find((n) => n.version === version) ?? null;
        setCurrent(notes);
        setVisible(true);
        // Даже без сводки запоминаем показанную версию.
        setString(SEEN_KEY, version);
      } catch {
        /* версия недоступна — не показываем */
      }
    })();
  }, []);

  if (!visible || !current) return null;

  return (
    <Dialog
      open
      onClose={() => setVisible(false)}
      title={`SportsDesk ${current.version}`}
      closeLabel="Закрыть"
      className="whatsnew-dialog"
      footer={
        <Button variant="primary" onClick={() => setVisible(false)}>
          Продолжить
        </Button>
      }
    >
      <span className="eyebrow">
        <Sparkles size={13} /> ЧТО НОВОГО
      </span>
      <ul className="whatsnew-list">
        {current.notes.map((n) => (
          <li key={n}>{n}</li>
        ))}
      </ul>
    </Dialog>
  );
}

export default WhatsNewDialog;
