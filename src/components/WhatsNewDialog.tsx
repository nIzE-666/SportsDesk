const SEEN_KEY = 'sportsdesk.whatsnew.seen';

export function WhatsNewDialog() {
  const panel = useRef<HTMLElement>(null);
  const [visible, setVisible] = useState(false);
  const [current, setCurrent] = useState<ChangeNotes | null>(null);
  useModalFocus(panel, visible && !!current, () => setVisible(false));

  useEffect(() => {
    if (!isTauriRuntime()) return;
    void (async () => {
      try {
        const mod = await import('@tauri-apps/api/app');
        const version = await mod.getVersion();
        const seen = getString(SEEN_KEY);
        if (seen === version) return;
        const notes = WHATS_NEW.find((n) => n.version === version) ?? null;
        setCurrent(notes);
        setVisible(true);
        // Даже без сводки запоминаем показанную версию.
        setString(SEEN_KEY, version);
      } catch {
        /* версия недоступна — не показываем */
      }
    })();
  }, []);

  if (!visible || !current) return null;

  return (
    <div className="whatsnew-scrim" onClick={() => setVisible(false)}>
      <section
        ref={panel}
        tabIndex={-1}
        className="panel whatsnew-card"
        role="dialog"
        aria-modal="true"
        aria-label="Что нового"
        onClick={(e) => e.stopPropagation()}
      >
        <button
          className="icon-button modal-close"
          onClick={() => setVisible(false)}
          aria-label="Закрыть"
        >
          <X size={18} />
        </button>
        <span className="eyebrow">
          <Sparkles size={13} /> ЧТО НОВОГО
        </span>
        <h2>SportsDesk {current.version}</h2>
        <ul>
          {current.notes.map((n) => (
            <li key={n}>{n}</li>
          ))}
        </ul>
        <button className="primary-btn" onClick={() => setVisible(false)}>
          Продолжить
        </button>
      </section>
    </div>
  );
}

export default WhatsNewDialog;
