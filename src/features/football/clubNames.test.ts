describe('clubKey', () => {
  for (const [league, { catalogue, table }] of Object.entries(LEAGUE_NAMES)) {
    it(`gives every ${league} table row exactly one catalogue club`, () => {
      const keys = catalogue.map(clubKey);
      expect(new Set(keys).size, 'catalogue clubs stay distinct').toBe(catalogue.length);
      const matched = table.map((name) => keys.filter((key) => key === clubKey(name)).length);
      expect(matched.filter((count) => count !== 1)).toEqual([]);
      expect(new Set(table.map(clubKey)).size, 'table clubs stay distinct').toBe(table.length);
    });
  }

  it.each([
    ['Inter Milan', 'Inter'],
    ['AC Milan', 'Milan'],
    ['AS Roma', 'Roma'],
    ['FC Bayern Munich', 'Bayern München'],
    ['Bayer 04 Leverkusen', 'Bayer Leverkusen'],
    ['1. FSV Mainz 05', 'Mainz 05'],
    ['FC Köln', '1. FC Köln'],
    ['RCD Espanyol de Barcelona', 'Espanyol'],
    ['RC Celta', 'Celta Vigo'],
    ['Stade Rennais FC', 'Rennes'],
    ['Havre Athletic Club', 'Le Havre'],
    ['Montreal Impact', 'CF Montréal'],
    ['Los Angeles Galaxy', 'LA Galaxy'],
    ['New York Red Bulls', 'Red Bull New York'],
    ['New York City Football Club', 'New York City FC'],
    ['St. Louis City SC', 'St. Louis City'],
  ])('joins %s and %s', (table, catalogue) => {
    expect(clubKey(table)).toBe(clubKey(catalogue));
  });

  it('joins the spellings of the Premier League table', () => {
    expect(clubKey('Bournemouth AFC')).toBe(clubKey('Bournemouth'));
    expect(clubKey('AFC Bournemouth')).toBe(clubKey('Bournemouth'));
    expect(clubKey('Brighton Hove Albion')).toBe(clubKey('Brighton'));
    expect(clubKey('Brighton & Hove Albion')).toBe(clubKey('Brighton'));
  });

  it('keeps different clubs apart', () => {
    const clubs = [
      'Bournemouth',
      'Bournemouth Women',
      'Paris FC',
      'Paris Saint-Germain',
      'Manchester City',
      'Manchester United',
      'Real Madrid',
      'Atlético Madrid',
      'Inter',
      'Inter Miami',
      'Los Angeles FC',
      'LA Galaxy',
      'Deportivo Alavés',
      'Deportivo A Coruña',
      'New York City FC',
      'Red Bull New York',
    ];
    expect(new Set(clubs.map(clubKey)).size).toBe(clubs.length);
  });

  it('never turns a name into nothing', () => {
    expect(clubKey('FC')).toBe('fc');
    expect(clubKey('1860')).toBe('1860');
  });
});
